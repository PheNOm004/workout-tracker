import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const input = JSON.parse(fs.readFileSync(path.join(root, "catalogue/exercises.json"), "utf8"));
const output = path.join(root, "app/src/main/java/com/lsing/timego/data/guidance/BundledCatalogue.kt");
const quote = (value) => JSON.stringify(value).replaceAll("$", "\\$");
const list = (values) => `listOf(${values.map(quote).join(", ")})`;
const nullable = (value) => value == null ? "null" : quote(value);
const rows = input.exercises.map((entry) => `    ExerciseGuidance(
        catalogueKey = ${quote(entry.key)}, name = ${quote(entry.name)}, catalogueVersion = ${input.catalogueVersion},
        aliases = ${list(entry.aliases)}, muscleGroups = ${list(entry.muscleGroups)}, equipment = ${list(entry.equipment)},
        difficulty = ${quote(entry.difficulty)}, complexity = ${quote(entry.complexity)}, purpose = ${quote(entry.purpose)},
        setup = ${list(entry.setup)}, steps = ${list(entry.steps)}, cues = ${list(entry.cues)}, mistakes = ${list(entry.mistakes)},
        easierVariationKey = ${nullable(entry.easierVariationKey)}, harderVariationKeys = ${list(entry.harderVariationKeys)}, reviewStatus = ${quote(entry.reviewStatus)},
    )`);
const chunks = [];
for (let index = 0; index < rows.length; index += 40) {
  const number = chunks.length;
  chunks.push(`private fun catalogueChunk${number}() = listOf(\n${rows.slice(index, index + 40).join(",\n")},\n)`);
}
const kotlin = `// Generated by scripts/generate-catalogue-kotlin.mjs. Do not edit by hand.
package com.lsing.timego.data.guidance

const val BUNDLED_CATALOGUE_VERSION = ${input.catalogueVersion}

${chunks.join("\n\n")}

val BUNDLED_EXERCISE_GUIDANCE: List<ExerciseGuidance> by lazy {
    listOf(${chunks.map((_, index) => `catalogueChunk${index}()`).join(", ")}).flatten()
}
`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, kotlin);
console.log(`Generated ${input.exercises.length} Kotlin guidance rows.`);
